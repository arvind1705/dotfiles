def _quote(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def _folded(column: str) -> str:
    return f"LOWER(REPLACE(TRIM({column}), '_', ' '))"


def normalize(column: str, scheme: str) -> str:
    """CASE expression mapping every listed source spelling to its label."""
    spec = RULES["normalizations"][scheme]
    whens = " ".join(
        f"WHEN {_quote(source)} THEN {_quote(label)}"
        for source, label in spec["map"].items()
    )
    fallback = f"TRIM({column})" if spec["unmapped"] == "keep" else "NULL"
    return f"CASE TRIM({column}) {whens} ELSE {fallback} END"


def in_set(column: str, value_set: str) -> str:
    """Whether a raw state column is in the set, ignoring case and separators."""
    folded = ", ".join(_quote(v) for v in RULES["valueSets"][value_set]["folded"])
    return f"COALESCE({_folded(column)} IN ({folded}), FALSE)"


def in_labels(column: str, value_set: str) -> str:
    """Whether an already-normalized column holds one of the set's labels."""
    labels = ", ".join(_quote(v) for v in RULES["valueSets"][value_set]["labels"])
    return f"COALESCE({column} IN ({labels}), FALSE)"


def lifecycle(column: str, finished: str, cancelled: str) -> str:
    """'finished', 'cancelled' or 'other' for a raw state column."""
    return (
        f"CASE WHEN {in_set(column, finished)} THEN 'finished' "
        f"WHEN {in_set(column, cancelled)} THEN 'cancelled' ELSE 'other' END"
    )


# ── Shared SQL helpers (not rules from the TTL) ─────────────────────────────
#
# Account scope. A caller may see a ticket raised by one of their accounts or
# sub-accounts, located at one of their sites or sub-sites, or affecting one of
# their devices. The org directory (account_count_summary) and the device
# inventory (standard_devices + device_account_mapping) are the authority, the
# same tables the Dgraph org and device ownership are loaded from.

# Account IDs in the scope lists are hex-encoded UTF-8: Cube's `contains` is a
# case-insensitive ILIKE, and lower-case hex makes that match exact.
def _hex(expr: str) -> str:
    return f"encode(convert_to({expr}, 'UTF8'), 'hex')"


_ORG_MAP = (
    "(SELECT {key}, string_agg(DISTINCT " + _hex("account_id") + ", ',') AS accounts "
    "FROM public.account_count_summary "
    "WHERE {key} IS NOT NULL AND account_id IS NOT NULL GROUP BY {key})"
)
_OWNER_MAP = (
    "(SELECT DISTINCT ON ({key}) {key}, account_id "
    "FROM public.account_count_summary WHERE {key} IS NOT NULL "
    "ORDER BY {key}, account_id)"
)
# Active device placements, keyed by serial (tickets reference devices by serial).
_DEVICE_MAP = (
    "(SELECT d.serial_number AS serial, a.account_id "
    "FROM public.standard_devices d "
    "JOIN public.device_account_mapping dam "
    "ON dam.device_id = d.device_id AND dam.is_active "
    "JOIN public.account_count_summary a ON a.id = dam.account_hierarchy_id "
    "WHERE d.serial_number IS NOT NULL AND a.account_id IS NOT NULL)"
)
_LEVELS = {
    "sub_account": "sub_account_id",
    "site": "site_id",
    "sub_site": "sub_site_id",
}


def _levels(levels: str) -> list[str]:
    names = [name.strip() for name in levels.split(",") if name.strip()]
    unknown = set(names) - set(_LEVELS)
    if unknown:
        raise ValueError(f"unknown scope levels: {sorted(unknown)}")
    return names


def scope_joins(
    alias: str, table: str, key: str, levels: str, device: str, extra_devices: str = ""
) -> str:
    """Joins resolving every account that may see a ticket.

    ``levels`` names the org columns the table has (``sub_account,site,sub_site``);
    ``device`` is its device serial column and ``extra_devices`` an optional
    comma-separated serial list column. Each mapping is aggregated once and
    hash-joined, never looked up per row.
    """
    joins = []
    for level in _levels(levels):
        column = _LEVELS[level]
        joins.append(
            f"LEFT JOIN {_ORG_MAP.format(key=column)} scope_{level} "
            f"ON scope_{level}.{column} = {alias}.{column}"
        )
        if level in ("sub_account", "site"):
            joins.append(
                f"LEFT JOIN {_OWNER_MAP.format(key=column)} owner_{level} "
                f"ON owner_{level}.{column} = {alias}.{column}"
            )
    serials = f"ARRAY[t.{device}]"
    if extra_devices:
        serials = (
            f"array_cat({serials}, "
            f"string_to_array(COALESCE(t.{extra_devices}, ''), ','))"
        )
    joins.append(
        "LEFT JOIN (SELECT t.{key} AS ticket_key, "
        f"string_agg(DISTINCT {_hex('dm.account_id')}, ',') AS accounts "
        f"FROM public.{table} t CROSS JOIN LATERAL unnest({serials}) s(serial) "
        f"JOIN {_DEVICE_MAP} dm ON dm.serial = TRIM(s.serial) "
        f"GROUP BY t.{key}) scope_device ON scope_device.ticket_key = {alias}.{key}"
        .format(key=key)
    )
    return " ".join(joins)


def scope_accounts(alias: str, levels: str) -> str:
    """Every account that may see the ticket, as ``,hex(A),hex(B),``.

    Cube's queryRewrite matches ``,hex(id),`` for each caller account.
    """
    parts = [_hex(f"{alias}.account_id")]
    parts += [f"scope_{level}.accounts" for level in _levels(levels)]
    parts.append("scope_device.accounts")
    return f"',' || concat_ws(',', {', '.join(parts)}) || ','"


def scope_account(alias: str, levels: str) -> str:
    """The owning account (for narrowing): its own, else its sub-account's or site's."""
    owners = [f"owner_{level}.account_id" for level in _levels(levels)
              if level in ("sub_account", "site")]
    return f"COALESCE({', '.join([f'{alias}.account_id', *owners])})"


def age_bucket(column: str) -> str:
    """Creation age bucket against the database clock (NULL without a time).

    The producer reads these buckets only when its own clock is the real one.
    """
    return (
        f"CASE WHEN {column} IS NULL THEN NULL "
        f"WHEN {column} >= NOW() - INTERVAL '1 day' THEN 'lt1d' "
        f"WHEN {column} >= NOW() - INTERVAL '3 days' THEN '1_3d' "
        f"WHEN {column} >= NOW() - INTERVAL '7 days' THEN '3_7d' "
        f"ELSE 'gt7d' END"
    )


def older_than(column: str, hours: int) -> str:
    """Whether a time column is at least ``hours`` old by the database clock."""
    return f"COALESCE({column} <= NOW() - INTERVAL '{int(hours)} hours', FALSE)"


